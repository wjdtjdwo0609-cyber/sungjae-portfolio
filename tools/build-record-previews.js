// Only the existing, approved/redacted public JPEGs are inputs. Never read raw scans.
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");
const { execFileSync } = require("child_process");
const root = path.join(__dirname, "..");
const input = path.join(root, "assets/images/records/scans-20261027");
const output = path.join(root, "assets/images/records/display");
fs.mkdirSync(output, { recursive: true });
const variants = {};
for (const name of fs.readdirSync(input).filter((name) => name.endsWith(".jpg")).sort()) {
  const source = path.join(input, name);
  const dimensions = JSON.parse(execFileSync("ffprobe", ["-v", "error", "-select_streams", "v:0", "-show_entries", "stream=width,height", "-of", "json", source], { encoding: "utf8" })).streams[0];
  const target = path.join(output, name.replace(/\.jpg$/, "-2400.webp"));
  const resize = dimensions.width > dimensions.height ? ["2400", "0"] : ["0", "2400"];
  execFileSync("cwebp", ["-quiet", "-q", "92", "-m", "6", "-sharp_yuv", "-metadata", "icc", "-resize", ...resize, source, "-o", target]);
  const previewDimensions = JSON.parse(execFileSync("ffprobe", ["-v", "error", "-select_streams", "v:0", "-show_entries", "stream=width,height", "-of", "json", target], { encoding: "utf8" })).streams[0];
  const original = "./" + path.relative(root, source).split(path.sep).join("/");
  variants[original] = {
    display: "./" + path.relative(root, target).split(path.sep).join("/"),
    width: previewDimensions.width, height: previewDimensions.height,
    originalWidth: dimensions.width, originalHeight: dimensions.height,
    bytes: fs.statSync(target).size, originalBytes: fs.statSync(source).size,
    sourceSha256: crypto.createHash("sha256").update(fs.readFileSync(source)).digest("hex")
  };
}
fs.writeFileSync(path.join(root, "assets/record-image-variants.js"),
  "// Generated by tools/build-record-previews.js. Display copies are resized/lossy; originals stay unchanged.\n" +
  "window.PORTFOLIO_RECORD_IMAGES = " + JSON.stringify(variants, null, 2) + ";\n");
const values = Object.values(variants);
console.log(JSON.stringify({ files: values.length, originalBytes: values.reduce((n, v) => n + v.originalBytes, 0), displayBytes: values.reduce((n, v) => n + v.bytes, 0), variants }, null, 2));
